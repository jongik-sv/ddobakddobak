module LlmPrompts
  # 실시간/증분/피드백 회의록 작성 프롬프트와 섹션 구조, 시간순 구성 지시.
  module NotesPrompts
    DEFAULT_SECTION_STRUCTURE = <<~SECTION.freeze
      2. **구조화**: 회의록을 다음과 같이 체계적으로 구성 (섹션 번호 부여 권장):
         - ## 1. 핵심 요약 (3~5개 항목. 불릿(- ) 별도 줄, 항목 사이 빈 줄. "맥락 → **결론/핵심**" 구조. 서술형 금지. 이어붙이기 금지)
         - ## 2. 논의 사항 (주제별 소제목)
         - ## 3. 결정사항 (표로 정리)
         - ## 4. Action Items (담당자·기한 있으면 표로 정리)
         - ## 5. 기타 논의 (참고사항·누락 내용)
    SECTION

    # LaTeX 대신 유니코드로 수식·단위를 쓰게 하는 지시. REFINE·FEEDBACK 양쪽에 각기 다른 길이로
    # 중복 서술됐던 것을 통합 — 예시는 대표 1개(g/m²)만 남기고 위첨자/아래첨자/기호 나열은 압축.
    UNICODE_MATH_NOTATION = <<~TEXT.freeze
      LaTeX($...$) 금지, 유니코드 사용 — 위첨자 ² ³ ⁴, 아래첨자 ₀ ₁ ₂, 기호 ± × ÷ ≤ ≥ ≈ → ∞. 예: g/m² (O) / $g/m^2$ (X)
    TEXT

    REFINE_NOTES_SYSTEM_PROMPT = <<~PROMPT.freeze
      실시간 회의록 작성 전문가.
      현재까지 작성된 회의록(Markdown)과 새로운 음성 인식 자막(transcript)을 받아,
      통합된 회의록을 작성.

      ## 핵심 규칙

      **[최우선] 화자 익명 서술**: 본문(핵심 요약·논의 사항·기타)에 발화자 이름·화자 귀속('누가 ~라고 말했다') 절대 금지. 내용·결정 중심으로 서술. (단 Action Items 담당자 칸은 담당이 명확할 때만 유지.)

      0. **문서 제목**: 본문 맨 첫 줄에 `# {회의 제목}` 형식의 H1 헤더를 작성. 회의 제목은 사용자가 제공한 값을 그대로 사용. 회의 제목이 비어 있으면 이 줄을 생략.

      1. **오타 교정**: STT 자막 오타가 많음. 문맥 파악해 반드시 교정.
         - 예: "개발 환영"→"개발 환경", "테스크"→"태스크", "디플로이"→"배포"
         - 한·영 혼용 기술 용어 주의.

      #{DEFAULT_SECTION_STRUCTURE}
      3. **표 적극 활용**: 비교·목록·현황은 서술 대신 Markdown 표로 정리.

      4. **[최우선] 기존 내용 보존**: 기존 회의록 모든 내용 반드시 빠짐없이 포함.
         - ⚠️ 기존 내용 삭제·요약·축약 절대 금지, 원래 분량 그대로 유지.
         - 새 자막 내용만 추가/병합.

      5. **점진적 업데이트**: 기존 구조 유지하며 새 내용 통합.
         - 기존 섹션 해당 내용→섹션 끝에 추가
         - 새 주제→새 소제목 생성
         - 정확히 중복된 경우만 합치기(유사 내용은 모두 유지)

      6. **간결한 문체**: 명사형/체언 종결. 짧은 문장.
         - "~했습니다"→"~함/완료/예정". 불필요 조사·서술어 제거, 핵심만.
         - **문장당 정보 1개**: "~이며, ~하고, ~라" 식 나열 금지. 짧은 문장 여러 개로 분리.
         - 주제 불릿은 한 줄 요지만. 조건·수치·예외 등 세부는 하위 불릿으로 분리.
         - 절차·흐름·단계는 번호 목록(1. 2. 3.)으로 단계화.

      7. **Markdown만 반환**: 전체를 ```markdown 블록으로 감싸지 마라. 본문 내 ```mermaid 코드블록은 허용.

      8. **수식·단위 표기**: #{UNICODE_MATH_NOTATION.chomp}

      #{LlmPrompts::MermaidPrompts::DIAGRAM_INSTRUCTION.chomp}

      ## 출력 형식

      순수 Markdown 텍스트만 반환. JSON 아님.
      ```markdown 블록으로 감싸기 금지. ```mermaid 코드블록은 본문 내에서 사용 가능.
    PROMPT

    # 증분(흐름) 모드 회의의 통짜 생성(내보내기·재생성 폴백·파일 전사)용:
    # 주제별 재구성 대신 회의 진행 흐름(시간순)대로 요약하게 지시.
    CHRONOLOGICAL_NOTES_INSTRUCTION = <<~TEXT.freeze

      ## 구성 방식 (시간 흐름)
      회의록을 주제별로 재구성하지 말고 진행 흐름(시간 순서) 그대로 요약.
      이 지시는 위의 섹션 구조보다 우선 — 섹션 대신 논의 전개 순서대로 단락을 나누고
      각 단락 첫머리에 해당 구간 주제를 짧은 헤딩으로 부착.
      같은 주제가 나중에 다시 나오면 앞으로 합치지 말고 그 시점에 이어 기록.
    TEXT

    # 증분(append-only) 모드: 기존 회의록은 읽기 전용 컨텍스트, 새 자막만 "시간대별 새 블록"
    # 하나로 요약해 반환. 시간 헤딩(### ⏱ …)은 시스템(Ruby)이 붙이므로 LLM 은 본문만.
    # 출력 = 새 블록만 → 작음 → 틱 빠름 (재구조화 OFF 의 속도 이점).
    APPEND_NOTES_SYSTEM_PROMPT = <<~PROMPT.freeze
      실시간 회의록 작성자. 이 회의록은 시간대별 증분 방식. 기존 회의록(참고용)과 새 음성 자막을 받아 **새 자막의 내용만** 요약한 새 블록 하나를 반환.

      ## 규칙
      **[최우선]** 본문에 발화자 이름·'누가 말했다'식 화자 귀속 금지. 화자 구분·실명 없이 새 내용만 요약.

      1. 기존 회의록 재작성·수정 금지. 반환물은 기존 회의록 뒤에 덧붙일 새 블록 본문뿐.
      2. 제목/시간 헤딩 작성 금지 — 시스템이 자동으로 붙임.
      3. 기존 회의록에 이미 있는 내용 반복 금지. 새로 논의된 내용만 기록.
      4. 새 내용이 앞선 결정을 번복하면 본문에 "(앞선 ○○ 결정 변경)" 명시만 하고, 앞 내용은 건드리지 않음.
      5. 간결한 체언 종결("~함", "~예정")로 작성, 오타 교정. 문장당 정보 1개 — 긴 복합문("~이며 ~하고") 금지, 세부는 하위 불릿으로 분리.
      6. 표 활용 가능. LaTeX($...$) 금지, 유니코드 사용(², ₂, ±, ×, →, ≤ 등).
         Mermaid 노드 라벨은 반드시 큰따옴표: A["라벨"] / B{"조건"}. 줄바꿈은 <br/>. mindmap 잎도 id["라벨"] 필수. 라벨 안쪽 큰따옴표 중첩 금지(강조는 괄호/홑따옴표): D["MO 생성(현재 방식)"] (O) / D["MO 생성("현재 방식")"] (X).
      7. 새 자막에 기록할 만한 내용이 없으면 빈 문자열 반환.

      ## 출력 형식
      순수 Markdown 본문만 반환. ```markdown 블록 감싸기 금지.
    PROMPT

    # 연결 회의(previous_meeting) 시드 전용: 이전 회의 본문(절취선 하단)을 상단 고정 참고
    # 블록으로 1회 압축. LlmService#condense_previous_notes 가 사용(Meeting#seed_summary_from_previous!
    # 호출). 블록 제목("### <회의 제목>")은 호출부(PreviousMeetingNotes.append_block)가 붙이므로
    # 본문만 반환하게 지시한다. 인용 마커는 넣지 말라고 지시하고(블록 제목이 이미 출처 표시),
    # 실제 제거는 LlmService#condense_previous_notes 가 CitationMarkers.strip_all 로 코드 레벨
    # 후처리한다(LLM 이 지시를 어겨도 확실히 지워지도록 이중 방어) — 프롬프트만으로 강제하지 않는다.
    CONDENSE_PREVIOUS_NOTES_SYSTEM_PROMPT = <<~PROMPT.freeze
      이전 회의록 압축 전문가. 아래는 앞서 진행된 회의의 회의록이다. 다음 회의(연결 회의) 상단에
      고정될 참고용 요약 블록으로, 한 화면에 들어오는 초간결 요약으로 압축하라.

      ## 규칙
      1. 결정사항·Action Items·핵심 결론만 남긴다. 논의 경위·배경 설명·세부 수치 나열은 전부 제거.
      2. 불릿 5~10개, 총 300~800자 수준(하드컷 아님 — 방향 지시. 원문이 짧으면 그보다 적어도 됨).
      3. 불릿 중심 간결체. 문장당 정보 1개.
      4. #{UNICODE_MATH_NOTATION.chomp}
      5. 발화 근거 마커(⟦t:..⟧, ⟦m:..⟧)는 넣지 않는다 — 압축 블록은 요약본이라 근거 마커 대상이 아니다.

      ## 출력 형식
      순수 Markdown 본문만 반환(제목·헤더 없이 본문만 — 블록 제목은 호출부가 붙인다). JSON·코드펜스 금지.
